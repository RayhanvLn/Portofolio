// Generates topographic contour paths used by ContourField and /public/svg.
// Run: node scripts/generate-contours.mjs
import { writeFileSync } from 'node:fs';

function contour(seed, rings, { w = 1000, h = 1000, cx = 0.5, cy = 0.5, spread = 540, aspect = 1.3 } = {}) {
  const out = [];
  for (let r = 0; r < rings; r++) {
    const base = 26 + r * (spread / rings);
    const steps = 72;
    let d = '';
    for (let i = 0; i <= steps; i++) {
      const a = (i / steps) * Math.PI * 2;
      const n =
        Math.sin(a * 3 + seed + r * 0.31) * 0.085 +
        Math.sin(a * 5 - seed * 1.7 + r * 0.22) * 0.045 +
        Math.cos(a * 2 + seed * 0.6 - r * 0.17) * 0.07;
      const rad = base * (1 + n);
      const x = w * cx + Math.cos(a) * rad * aspect;
      const y = h * cy + Math.sin(a) * rad;
      d += `${i === 0 ? 'M' : 'L'}${x.toFixed(1)} ${y.toFixed(1)}`;
    }
    out.push(d + 'Z');
  }
  return out;
}

const sets = {
  one: contour(1.3, 16, { cx: 0.62, cy: 0.46 }),
  two: contour(4.1, 14, { cx: 0.3, cy: 0.6, aspect: 1.15 }),
};

writeFileSync(
  'src/components/ContourField/contourData.ts',
  `// Generated by scripts/generate-contours.mjs — do not edit by hand.\n` +
    `export const CONTOUR_VIEWBOX = '0 0 1000 1000';\n` +
    `export const contourSets = ${JSON.stringify(sets, null, 2)} as const;\n` +
    `export type ContourVariant = keyof typeof contourSets;\n`,
);

for (const [name, paths] of Object.entries({ '01': sets.one, '02': sets.two })) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" fill="none" stroke="#F1F0E9" stroke-width="1.2" stroke-linejoin="round">\n${paths
    .map((d) => `  <path d="${d}"/>`)
    .join('\n')}\n</svg>\n`;
  writeFileSync(`public/svg/contour-${name}.svg`, svg);
}

